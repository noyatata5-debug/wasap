-- 1. Buat Tabel Users
CREATE TABLE IF NOT EXISTS public.users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username TEXT UNIQUE NOT NULL,
  phone_number TEXT UNIQUE NOT NULL,
  password_hash TEXT NOT NULL,
  role TEXT DEFAULT 'user', -- 'admin' | 'user'
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Tambahkan kolom phone_number ke tabel tasks & expenses jika belum ada
ALTER TABLE public.tasks 
ADD COLUMN IF NOT EXISTS phone_number TEXT;

ALTER TABLE public.expenses 
ADD COLUMN IF NOT EXISTS phone_number TEXT;

-- 3. Buat Index agar query pencarian per nomor WA super cepat
CREATE INDEX IF NOT EXISTS idx_tasks_phone ON public.tasks(phone_number);
CREATE INDEX IF NOT EXISTS idx_expenses_phone ON public.expenses(phone_number);
CREATE INDEX IF NOT EXISTS idx_users_phone ON public.users(phone_number);
CREATE INDEX IF NOT EXISTS idx_users_username ON public.users(username);

-- 4. Aktifkan Row Level Security (RLS) atau Realtime Replication
ALTER PUBLICATION supabase_realtime ADD TABLE public.tasks;
ALTER PUBLICATION supabase_realtime ADD TABLE public.expenses;
ALTER PUBLICATION supabase_realtime ADD TABLE public.users;
